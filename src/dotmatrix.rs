/// Render `text` as dots. `dot` is the diameter in px, `gap` the space between dots.
pub fn render_pixmap(text: &str, dot: f32, gap: f32, color: [u8; 3], ghost: bool) -> Pixmap {
    let chars: Vec<char> = text.chars().collect();
    let pitch = dot + gap;
    let cols = if chars.is_empty() { 1 } else { chars.len() * 6 - 1 };
    let w = ((cols as f32 * pitch) - gap).ceil().max(1.0) as u32 + 2;
    let h = ((7.0 * pitch) - gap).ceil() as u32 + 2;
    let mut pm = Pixmap::new(w, h).unwrap();
    // one path per colour: much cheaper than filling every dot separately
    let mut lit_pb = PathBuilder::new();
    let mut dim_pb = PathBuilder::new();
    for (ci, ch) in chars.iter().enumerate() {
        let g = glyph(*ch);
        let blank = *ch == ' ';
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                let on = bits >> (4 - col) & 1 == 1;
                if !on && (!ghost || blank) {
                    continue;
                }
                let cx = 1.0 + (ci * 6 + col) as f32 * pitch + dot / 2.0;
                let cy = 1.0 + row as f32 * pitch + dot / 2.0;
                if on { &mut lit_pb } else { &mut dim_pb }.push_circle(cx, cy, dot / 2.0);
            }
        }
    }
    let fill = |pm: &mut Pixmap, pb: PathBuilder, a: u8| {
        if let Some(path) = pb.finish() {
            let mut paint = Paint::default();
            paint.set_color_rgba8(color[0], color[1], color[2], a);
            paint.anti_alias = true;
            pm.fill_path(&path, &paint, tiny_skia::FillRule::Winding, Transform::identity(), None);
        }
    };
    fill(&mut pm, dim_pb, 30);
    fill(&mut pm, lit_pb, 255);
    pm
}

pub fn to_image(pm: &Pixmap) -> slint::Image {
    let buf = slint::SharedPixelBuffer::<slint::Rgba8Pixel>::clone_from_slice(pm.data(), pm.width(), pm.height());
    slint::Image::from_rgba8_premultiplied(buf)
}
